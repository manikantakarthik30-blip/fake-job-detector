@st.cache_resource(show_spinner="Loading saved model...")
def load_model(path: str, modified_time: float):
    """Cache one model per artifact path/version. Never train during app startup."""
    del modified_time
    artifact = joblib.load(path)
    if not isinstance(artifact, dict) or not {"pipeline", "threshold"} <= artifact.keys():
        raise ValueError("Invalid model.joblib: pipeline and threshold are required.")
    if not 0 <= float(artifact["threshold"]) <= 1:
        raise ValueError("Model threshold must be between 0 and 1.")
    return artifact


@st.cache_data(show_spinner=False)
def load_metrics(path: str, modified_time: float):
    del modified_time
    with open(path, encoding="utf-8") as stream:
        return json.load(stream)


def get_model():
    if not MODEL_PATH.is_file():
        return None
    try:
        return load_model(str(MODEL_PATH.resolve()), MODEL_PATH.stat().st_mtime)
    except Exception:
        logger.exception("Saved model could not be loaded")
        st.warning("Saved model unavailable or invalid. Rule-based fallback is active.")
        return None


def top_reasons(record, prediction, model_used):
    text = clean_text(" ".join(str(record.get(k, "") or "") for k in
                               ("title", "company_profile", "company", "description", "requirements")))
    reasons = [f"Red-flag phrase: {flag}" for flag in RED_FLAGS if flag in text]
    description = clean_text(record.get("description", ""))
    if description and len(description.split()) < 40:
        reasons.append(f"Very short description ({len(description.split())} words)")
    if not clean_text(record.get("company_profile", record.get("company", ""))):
        reasons.append("Company information is missing")
    if not clean_text(record.get("requirements", "")):
        reasons.append("Requirements are missing")
    if str(record.get("has_company_logo", 1)).lower() in {"0", "false", "no"}:
        reasons.append("Company logo is not provided")
    if model_used:
        reasons.extend(f"Model signal: '{x['term']}' is associated with fraud in training"
                       for x in prediction.get("top_signals", []) if x.get("direction") == "fraud")
    return list(dict.fromkeys(reasons))[:5] or ["No configured warning indicators were found"]


def show_result(probability, verdict, threshold, reasons, model_used):
    pct = max(0, min(100, probability * 100))
    color = "#FF4757" if verdict == "LIKELY_FRAUDULENT" else "#2ED573"
    st.markdown(f"<h2 style='color:{color}'>{verdict.replace('_', ' ')}</h2>", unsafe_allow_html=True)
    st.metric("Estimated fraud probability", f"{pct:.1f}%",
              f"Decision threshold: {threshold * 100:.1f}%")
    st.progress(int(round(pct)), text=f"Probability gauge: {pct:.1f}%")
    st.markdown("**Top 5 reasons / indicators**")
    for reason in reasons:
        st.markdown(f"- {reason}")
    st.caption("Saved ML model" if model_used else "Rule-based fallback; this score is not an ML probability.")
    st.caption("Decision support only. Verify the employer independently; this is not proof of fraud.")


def show_model_card():
    st.subheader("Model card")
    if not METRICS_PATH.is_file():
        st.warning("metrics.json is missing. Add the output generated by train.py.")
        return
    try:
        m = load_metrics(str(METRICS_PATH.resolve()), METRICS_PATH.stat().st_mtime)
    except (OSError, json.JSONDecodeError):
        logger.exception("Could not read metrics.json")
        st.error("metrics.json is invalid or unreadable.")
        return
    cv, test, counts = m.get("cross_validation", {}), m.get("test", {}), m.get("class_counts", {})
    a, b, c = st.columns(3)
    a.metric("Dataset rows", f"{m.get('rows_after_deduplication', 0):,}")
    b.metric("Fraudulent examples", f"{counts.get('fraudulent', 0):,}")
    c.metric("Threshold", f"{m.get('selected_threshold', 0):.4f}")
    st.write(f"**Dataset:** {m.get('dataset', 'Not recorded')}  ")
    st.write(f"**Model:** {m.get('model', 'Not recorded')}  ")
    st.write(f"**Validation:** {cv.get('folds', '—')}-fold {cv.get('method', 'CV')}; SMOTE in training pipeline: {cv.get('smote_inside_pipeline', '—')}")
    st.markdown("#### Cross-validation")
    st.write(f"Mean PR-AUC: **{m.get('cv_pr_auc_mean', 0):.4f} ± {m.get('cv_pr_auc_std', 0):.4f}**")
    st.markdown("#### Holdout test")
    cols = st.columns(4)
    for col, label, key in zip(cols, ("PR-AUC", "F1", "Precision", "Recall"),
                               ("pr_auc", "f1", "precision", "recall")):
        col.metric(label, f"{test.get(key, 0):.4f}")
    st.caption(f"Test rows: {test.get('n', 0):,}; positives: {test.get('positive_count', 0):,}")
    st.markdown("#### Known limitations")
    for item in (
        "Historical EMSCAD data may not represent current scam patterns.",
        "English-language dataset; other-language performance is unknown.",
        "Class imbalance, sampling and historical label errors may introduce bias.",
        "Scores are not guaranteed to be calibrated for current job listings.",
        "A missing logo or short description is not proof of fraud.",
    ):
        st.markdown(f"- {item}")
    st.write("**Training date:** Not recorded in metrics.json.")


st.title("🛡️ Fake Job & Internship Detector")
st.caption("AI-assisted screening for potentially fraudulent job listings")
model = get_model()
if model is None:
    st.info("Using rule-based fallback until a valid model.joblib is available.")

single, batch, card, about = st.tabs(["Check one listing", "Batch CSV", "Model card", "How it works"])
with single:
    st.subheader("Check one listing")
    left, right = st.columns(2)
    with left:
        title = st.text_input("Job title", placeholder="Software Engineer")
        company = st.text_input("Company", placeholder="Company name")
        logo = st.radio("Company logo present?", ["Yes", "No"], horizontal=True)
    with right:
        description = st.text_area("Description", height=150, placeholder="Paste the job description...")
        requirements = st.text_area("Requirements", height=100, placeholder="Skills and qualifications...")
    if st.button("Check listing", type="primary", use_container_width=True):
        record = {"title": title, "company_profile": company, "description": description,
                  "requirements": requirements, "has_company_logo": int(logo == "Yes")}
        if not any(str(record[k]).strip() for k in ("title", "company_profile", "description", "requirements")):
            st.error("Enter a title, company, description, or requirements.")
        else:
            try:
                if model is not None:
                    result = predict_one(record, model_artifact=model)
                    p, verdict, threshold = result["probability"], result["verdict"], result["threshold"]
                else:
                    result = rule_based_prediction(record)
                    p, verdict, threshold = result["probability"], result["verdict"], 0.40
                show_result(p, verdict, threshold, top_reasons(record, result, model is not None), model is not None)
            except (ValueError, KeyError, TypeError) as exc:
                logger.warning("Single prediction rejected: %s", exc)
                st.error(f"Could not score listing: {exc}")
            except Exception:
                logger.exception("Unexpected single prediction failure")
                st.error("Prediction failed. Check the model artifact and application logs.")

with batch:
    st.subheader("Batch analysis")
    st.caption("CSV limit: 20 MB and 20,000 rows. Requires at least one job-text column.")
    upload = st.file_uploader("Upload job listings CSV", type=["csv"], key="batch_csv")
    if upload is not None:
        try:
            if upload.size > MAX_UPLOAD_BYTES:
                raise ValueError("CSV exceeds the 20 MB upload limit.")
            frame = validate_csv(upload.getvalue())
            st.success(f"Validated {len(frame):,} listings.")
            if st.button("Analyze CSV", type="primary"):
                records = frame.to_dict(orient="records")
                if model is not None:
                    probabilities = predict_many(records, model_artifact=model)
                    threshold, source = float(model["threshold"]), "saved_model"
                else:
                    fallback = [rule_based_prediction(row) for row in records]
                    probabilities = [x["probability"] for x in fallback]
                    threshold, source = 0.40, "rule_based_fallback"
                verdicts = ["LIKELY_FRAUDULENT" if p >= threshold else "LIKELY_LEGITIMATE"
                            for p in probabilities]
                out = frame.copy()
                out["FAKE_PROBABILITY"] = [round(p * 100, 2) for p in probabilities]
                out["PREDICTION"] = [int(v == "LIKELY_FRAUDULENT") for v in verdicts]
                out["VERDICT"] = verdicts
                out["SPLIT"] = source
                out["CONFIDENCE"] = [round(max(p, 1 - p) * 100, 2) for p in probabilities]
                st.session_state["batch_results"] = out
                logger.info("Batch scored rows=%d source=%s", len(out), source)
        except ValueError as exc:
            st.error(str(exc))
        except Exception:
            logger.exception("Batch CSV processing failed")
            st.error("CSV analysis failed. Check the file format and application logs.")
    if st.session_state.get("batch_results") is not None:
        out = st.session_state["batch_results"]
        st.dataframe(out, use_container_width=True, hide_index=True)
        st.download_button("Download results CSV", out.to_csv(index=False).encode("utf-8"),
                           file_name="fake_job_results.csv", mime="text/csv")

with card:
    show_model_card()
with about:
    st.subheader("How it works")
    st.markdown("""
    - Single and batch listings use the saved TF-IDF + Logistic Regression pipeline.
    - The saved threshold controls the model verdict.
    - Text heuristics (red flags, short text, missing company/requirements, no logo) are displayed as indicators.
    - If the saved artifact is missing, a transparent rule-based fallback is used.

    **Ethical use:** This assists human review; it is not a final judgment. Do not use it alone to reject applicants, accuse employers, or make legal or financial decisions.
    """)
